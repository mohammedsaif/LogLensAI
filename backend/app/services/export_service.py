"""JSON and Markdown exports of a completed analysis."""

import json
from typing import Any

from app.ai.summary import SUMMARY_LABELS
from app.db.models import Analysis, SignalRow


def export_payload(row: Analysis, signals: list[SignalRow]) -> dict[str, Any]:
    stats = dict(row.stats or {})
    return {
        "export_version": "1.0",
        "analysis_id": row.id,
        "filename": row.filename,
        "created_at": row.created_at.isoformat() if row.created_at else None,
        "completed_at": row.completed_at.isoformat() if row.completed_at else None,
        "ai": {
            "status": row.ai_status,
            "provider": row.ai_provider,
            "model": row.ai_model,
            "prompt_version": row.prompt_version,
            "confidence": row.confidence,
        },
        "summary_lines": row.summary_lines,
        "analysis": row.analysis,
        "critical_signals": [
            {
                "kind": s.kind,
                "severity": s.severity,
                "line_no": s.line_no,
                "timestamp": s.ts.isoformat() if s.ts else None,
                "service": s.service,
                "message": s.message,
                "reason": s.reason,
                "must_include": s.must_include,
            }
            for s in signals
        ],
        "evidence": row.evidence,
        "stats": stats,
        "redaction_counts": row.redaction_counts,
    }


def export_json(row: Analysis, signals: list[SignalRow]) -> str:
    return json.dumps(export_payload(row, signals), indent=2, ensure_ascii=False, default=str)


def _md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def export_markdown(row: Analysis, signals: list[SignalRow]) -> str:
    analysis = row.analysis or {}
    stats = row.stats or {}
    evidence = (row.evidence or {}).get("items", [])
    out: list[str] = [
        f"# Incident report: {analysis.get('incident_title', row.filename)}",
        "",
        f"- **File:** `{row.filename}` ({stats.get('total_lines', 0)} lines)",
        f"- **Analysis ID:** `{row.id}`",
        f"- **AI:** {row.ai_provider} / {row.ai_model} ({row.ai_status}), prompt `{row.prompt_version}`",
        f"- **Confidence:** {row.confidence} (qualitative; hypotheses are not confirmed causes)",
        "",
        "## Five-line summary",
        "",
    ]
    for line in row.summary_lines or []:
        label, _, rest = line.partition(":")
        out.append(
            f"- **{label}:**{rest}" if label in SUMMARY_LABELS or label.startswith("Possible Cause") else f"- {line}"
        )
    out += ["", "## Critical signals (deterministically preserved)", ""]
    must = [s for s in signals if s.must_include]
    if must:
        out += ["| Line | Time | Severity | Service | Message | Why flagged |", "|---|---|---|---|---|---|"]
        for s in must:
            out.append(
                f"| L{s.line_no} | {s.ts.isoformat() if s.ts else '-'} | {s.severity} | {s.service or '-'} | "
                f"{_md_escape(s.message[:160])} | {_md_escape(s.reason)} |"
            )
    else:
        out.append("_None._")
    out += ["", "## Observed facts", ""]
    out += [f"- {f['statement']} ({', '.join(f['evidence_ids'])})" for f in analysis.get("observed_facts", [])]
    out += ["", "## Hypotheses (not confirmed)", ""]
    hyps = analysis.get("hypotheses", [])
    out += [f"- _{h['confidence']} confidence:_ {h['statement']} ({', '.join(h['evidence_ids'])})" for h in hyps] or [
        "_None._"
    ]
    out += ["", "## Recommended actions", ""]
    out += [f"- **{r['priority']}:** {r['action']}" for r in analysis.get("recommendations", [])]
    if analysis.get("uncertainty_notes"):
        out += ["", "## Uncertainty", ""] + [f"- {n}" for n in analysis["uncertainty_notes"]]
    out += ["", "## Evidence", "", "| ID | Lines | Count | Severity | Service | Text |", "|---|---|---|---|---|---|"]
    for e in evidence:
        lines = f"L{e['first_line']}" if e["first_line"] == e["last_line"] else f"L{e['first_line']}–L{e['last_line']}"
        out.append(
            f"| {e['id']}{' ★' if e.get('must_include') else ''} | {lines} | {e['count']} | {e['severity']} | "
            f"{e.get('service') or '-'} | {_md_escape(e['text'][:160])} |"
        )
    sev = stats.get("severity_counts", {})
    out += [
        "",
        "## Statistics",
        "",
        "- Severity: " + ", ".join(f"{k} {v}" for k, v in sev.items() if v),
        f"- Time range: {stats.get('time_range', {}).get('start')} → {stats.get('time_range', {}).get('end')}",
        f"- Malformed lines: {stats.get('malformed_lines', 0)}",
        f"- Redactions applied before AI: {row.redaction_counts or {}}",
        "",
        "_Generated by LogLens AI. Evidence text is redacted; line numbers refer to the original file._",
    ]
    return "\n".join(out) + "\n"
